// Run only inside an explicitly selected disposable Linux host with system libvirt.
func TestDedicatedMemoryLibvirt(t *testing.T) {
	if os.Getenv("NEX_MEMORY_LIBVIRT_TEST") != "1" {
		t.Skip("set NEX_MEMORY_LIBVIRT_TEST=1 in a disposable libvirt host")
	}
	if os.Geteuid() != 0 {
		t.Fatal("disposable lab root privileges required")
	}
	virsh := func(t *testing.T, args ...string) []byte {
		t.Helper()
		ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
		defer cancel()
		out, err := exec.CommandContext(ctx, "virsh", append([]string{"-c", "qemu:///system"}, args...)...).CombinedOutput()
		if err != nil {
			t.Fatalf("virsh %v: %v: %s", args, err, out)
		}
		return out
	}
	t.Logf("%s", virsh(t, "version"))
	for _, mode := range []string{"maximum", "dedicated"} {
		t.Run(mode, func(t *testing.T) {
			idBytes := make([]byte, 16)
			if _, err := rand.Read(idBytes); err != nil {
				t.Fatal(err)
			}
			id := fmt.Sprintf("%x-%x-%x-%x-%x", idBytes[:4], idBytes[4:6], idBytes[6:8], idBytes[8:10], idBytes[10:])
			name := "nex-memory-test-" + id
			spec := protocol.VMCreateSpec{ID: id, Name: name, CPU: protocol.VMCPU{Count: 1, Model: "host-passthrough"}, Memory: protocol.VMMemory{Mode: mode, SizeMiB: 512}, Boot: protocol.VMBoot{MediaBootOrder: 1}}
			body, err := managedDomainXML(spec, nil, nil, nil, "sda", "")
			if err != nil {
				t.Fatal(err)
			}
			path := filepath.Join(t.TempDir(), "domain.xml")
			if err := os.WriteFile(path, body, 0600); err != nil {
				t.Fatal(err)
			}
			t.Cleanup(func() {
				// UUIDs are generated by this test; never enumerate or touch existing domains.
				ctx, cancel := context.WithTimeout(context.Background(), 15*time.Second)
				defer cancel()
				exec.CommandContext(ctx, "virsh", "-c", "qemu:///system", "destroy", id).CombinedOutput()
				out, err := exec.CommandContext(ctx, "virsh", "-c", "qemu:///system", "undefine", id).CombinedOutput()
				if err != nil {
					t.Errorf("cleanup own domain: %v: %s", err, out)
				}
			})
			virsh(t, "define", path)
			virsh(t, "start", id, "--paused")
			live := virsh(t, "dumpxml", id)
			if err := validateManagedDefinition(virsh(t, "dumpxml", id, "--inactive"), body); err != nil {
				t.Fatalf("libvirt normalized persistent definition: %v", err)
			}
			var domain struct {
				Backing struct {
					Locked     *struct{} `xml:"locked"`
					NoShare    *struct{} `xml:"nosharepages"`
					Allocation struct {
						Mode string `xml:"mode,attr"`
					} `xml:"allocation"`
				} `xml:"memoryBacking"`
			}
			if err := xml.Unmarshal(live, &domain); err != nil {
				t.Fatal(err)
			}
			pid, err := os.ReadFile("/run/libvirt/qemu/" + name + ".pid")
			if err != nil {
				t.Fatal(err)
			}
			status, err := os.ReadFile("/proc/" + strings.TrimSpace(string(pid)) + "/status")
			if err != nil {
				t.Fatal(err)
			}
			values := map[string]int64{}
			for _, line := range strings.Split(string(status), "\n") {
				fields := strings.Fields(line)
				if len(fields) >= 2 && (fields[0] == "VmRSS:" || fields[0] == "VmLck:" || fields[0] == "VmSwap:") {
					values[fields[0]], err = strconv.ParseInt(fields[1], 10, 64)
					if err != nil {
						t.Fatal(err)
					}
				}
			}
			t.Logf("paused 512 MiB %s: RSS=%d KiB locked=%d KiB swap=%d KiB", mode, values["VmRSS:"], values["VmLck:"], values["VmSwap:"])
			if mode == "dedicated" {
				if domain.Backing.Locked == nil || domain.Backing.NoShare == nil || domain.Backing.Allocation.Mode != "immediate" {
					t.Fatal("live libvirt XML lacks dedicated backing")
				}
				if values["VmRSS:"] < 512*1024 || values["VmLck:"] < 512*1024 || values["VmSwap:"] != 0 {
					t.Fatal("guest RAM was not resident and locked before guest execution")
				}
			} else if values["VmLck:"] != 0 || values["VmRSS:"] >= 256*1024 {
				t.Fatal("maximum-mode RAM unexpectedly allocated or locked before guest execution")
			}
			virsh(t, "destroy", id)
			if _, err := os.Stat("/proc/" + strings.TrimSpace(string(pid))); !os.IsNotExist(err) {
				t.Fatalf("QEMU process remains after stop: %v", err)
			}
			t.Log("stopped domain released QEMU process and its memory")
		})
	}
	t.Run("legacy-stopped-save", func(t *testing.T) {
		ctx, cancel := context.WithTimeout(context.Background(), 60*time.Second)
		defer cancel()
		storagePath, err := os.MkdirTemp("/var/lib/libvirt/images", "nex-memory-upgrade-")
		if err != nil {
			t.Fatal(err)
		}
		t.Cleanup(func() {
			if err := os.RemoveAll(storagePath); err != nil {
				t.Error(err)
			}
		})
		if err := os.Chmod(storagePath, 0755); err != nil {
			t.Fatal(err)
		}
		e := NewManaged(t.TempDir())
		apply := func(c protocol.Command) {
			t.Helper()
			result, err := e.Execute(ctx, c, nil)
			if err != nil || result.Status != "succeeded" {
				t.Fatalf("%s: result=%+v error=%v", c.Kind, result, err)
			}
		}
		storage := protocol.StorageRegistration{ID: hostID(), PoolID: "memory-test-pool", HostID: "memory-test-host", Name: "Memory test storage", Path: storagePath}
		apply(protocol.Command{OperationID: hostID(), Kind: "storage-register", Storage: &storage})
		rawID := hostID()
		id := rawID[:8] + "-" + rawID[8:12] + "-" + rawID[12:16] + "-" + rawID[16:20] + "-" + rawID[20:]
		spec := protocol.VMCreateSpec{ID: id, PoolID: storage.PoolID, HostID: storage.HostID, Name: "nex-memory-upgrade-" + hostID(), GuestOS: "linux", CPU: protocol.VMCPU{Count: 1, Model: "host-passthrough"}, Memory: protocol.VMMemory{Mode: "dedicated", SizeMiB: 512}, Disks: []protocol.VMDisk{{StorageID: storage.ID, Name: "system", SizeGiB: 1, Bus: "virtio", BootOrder: 1, Thin: true}}, Boot: protocol.VMBoot{Firmware: "bios"}}
		t.Cleanup(func() {
			cleanupCtx, cleanupCancel := context.WithTimeout(context.Background(), 15*time.Second)
			defer cleanupCancel()
			exec.CommandContext(cleanupCtx, "virsh", "-c", "qemu:///system", "destroy", spec.ID).CombinedOutput()
			out, err := exec.CommandContext(cleanupCtx, "virsh", "-c", "qemu:///system", "undefine", spec.ID).CombinedOutput()
			if err != nil {
				t.Errorf("cleanup own upgrade domain: %v: %s", err, out)
			}
		})
		apply(protocol.Command{OperationID: hostID(), Kind: "vm-create", VM: &spec})
		journals, err := e.journals()
		if err != nil {
			t.Fatal(err)
		}
		old, err := managedCurrent(journals, spec.ID)
		if err != nil {
			t.Fatal(err)
		}
		var legacy managedDomain
		if err := xml.Unmarshal(old.Domain, &legacy); err != nil {
			t.Fatal(err)
		}
		legacy.MemoryBacking = nil
		old.Domain, err = xml.Marshal(legacy)
		if err != nil {
			t.Fatal(err)
		}
		legacyPath := filepath.Join(t.TempDir(), "legacy.xml")
		if err := os.WriteFile(legacyPath, old.Domain, 0600); err != nil {
			t.Fatal(err)
		}
		virsh(t, "define", legacyPath)
		if err := e.save(old); err != nil {
			t.Fatal(err)
		}
		spec.Revision++
		apply(protocol.Command{OperationID: hostID(), Kind: "vm-update", VM: &spec})
		journals, err = e.journals()
		if err != nil {
			t.Fatal(err)
		}
		updated, err := managedCurrent(journals, spec.ID)
		if err != nil {
			t.Fatal(err)
		}
		if updated.Command.VM.ID != old.Command.VM.ID || updated.Command.VM.Revision != 1 || len(updated.Disks) != 1 || updated.Disks[0] != old.Disks[0] {
			t.Fatal("upgrade changed identity or disk ownership")
		}
		if err := validateManagedDefinition(virsh(t, "dumpxml", spec.ID, "--inactive"), updated.Domain); err != nil {
			t.Fatal(err)
		}
		var actual managedDomain
		if err := xml.Unmarshal(updated.Domain, &actual); err != nil {
			t.Fatal(err)
		}
		if actual.MemoryBacking == nil {
			t.Fatal("stopped save did not add memory backing")
		}
		virsh(t, "start", spec.ID, "--paused")
		pid, err := os.ReadFile("/run/libvirt/qemu/" + spec.Name + ".pid")
		if err != nil {
			t.Fatal(err)
		}
		status, err := os.ReadFile("/proc/" + strings.TrimSpace(string(pid)) + "/status")
		if err != nil {
			t.Fatal(err)
		}
		locked := int64(0)
		for _, line := range strings.Split(string(status), "\n") {
			if fields := strings.Fields(line); len(fields) >= 2 && fields[0] == "VmLck:" {
				locked, err = strconv.ParseInt(fields[1], 10, 64)
				if err != nil {
					t.Fatal(err)
				}
			}
		}
		if locked < 512*1024 {
			t.Fatalf("upgraded VM not locked: %d KiB", locked)
		}
		t.Logf("real ManagedEngine create, legacy journal simulation, stopped vm-update revision 1 and paused start passed; UUID/disk preserved; locked=%d KiB", locked)
	})

	t.Run("insufficient-memlock", func(t *testing.T) {
		ctx, cancel := context.WithTimeout(context.Background(), 15*time.Second)
		defer cancel()
		out, err := exec.CommandContext(ctx, "setpriv", "--bounding-set=-ipc_lock", "prlimit", "--memlock=8388608:8388608", "--", "qemu-system-x86_64", "-machine", "q35,accel=tcg", "-m", "64", "-display", "none", "-nodefaults", "-overcommit", "mem-lock=on", "-S").CombinedOutput()
		if ctx.Err() != nil || err == nil || !strings.Contains(strings.ToLower(string(out)), "lock") {
			t.Fatalf("expected immediate memlock failure, got %v: %s", err, out)
		}
		t.Logf("64 MiB QEMU with 8 MiB memlock limit failed safely: %s", out)
	})
}
