"""Guest continuity across pool authority operations, in an explicitly selected disposable lab.

Phase 4 accepted planned master change and fence-verified promotion with an *empty* VM
inventory, so nothing established that running guests survive them. This harness samples
tamper-evident continuity signals around an operation and reports whether any guest was
restarted.

Signals, and why this combination. A restart cannot leave all of them unchanged:

  host side   host_boot_id  the host itself did not reboot under us
              pid           a replaced QEMU process gets a new pid
              starttime     /proc/<pid>/stat field 22; strictly increases on re-exec, so it
                            closes the pid-reuse hole that pid alone leaves open
              domid         libvirt's per-run domain ID, monotonic within a libvirtd run
  guest side  boot_id       /proc/sys/kernel/random/boot_id, regenerated by the guest kernel
                            on every boot; catches an in-guest reboot that keeps the same
                            QEMU process, which no host-side signal can see
              heartbeat     the guest appends <epoch> <boot_id> to its own disk every second

`virsh domstate --reason` is deliberately NOT a pass criterion. It reports `running (booted)`
for a domain's whole life, so it reads identical before and after a destroy+start. It is
recorded only so the evidence shows what it would have claimed.

The guest side is read from the VM's disk on shared storage, by a host that is not running
it, because Nex gives managed domains no serial or console device.

Run the arms in order. Arm B must fail the comparison: a continuity check nobody has seen
detect a restart is not evidence.
"""
import argparse
import json
import subprocess
import sys
import time
from pathlib import Path

import cluster_ha_lab as lab_mod

# Host-side probe. Resolves the QEMU pid by matching the VM UUID in /proc/<pid>/cmdline
# rather than trusting a pidfile name, and splits /proc/<pid>/stat after the final ')'
# because the comm field may itself contain spaces.
HOST_PROBE = r"""
uuid=%s
echo "host_boot_id=$(cat /proc/sys/kernel/random/boot_id)"
echo "libvirtd_start=$(systemctl show -p ActiveEnterTimestampMonotonic --value libvirtd)"
pid=""
for p in /proc/[0-9]*; do
  tr '\0' '\n' < "$p/cmdline" 2>/dev/null | grep -qFx -- "$uuid" && { pid="${p#/proc/}"; break; }
done
echo "pid=$pid"
if [ -n "$pid" ]; then
  echo "starttime=$(sed -e 's/.*) //' /proc/$pid/stat | cut -d' ' -f20)"
fi
echo "domid=$(virsh -c qemu:///system domid $uuid 2>/dev/null | tr -d ' \n')"
echo "domstate=$(virsh -c qemu:///system domstate --reason $uuid 2>/dev/null | head -1 | tr -d '\n')"
"""

# Guest heartbeat slot: one 512-byte record the guest rewrites in place each second.
HEARTBEAT_OFFSET = 1048576
HEARTBEAT_BYTES = 80

# Signals that must all be unchanged for a guest to count as continuous.
CONTINUITY_FIELDS = ("host_boot_id", "pid", "starttime", "domid")


def host_sample(lab, host, vm):
    result = lab_mod.ssh(lab, host, HOST_PROBE % vm, check=False)
    fields = {}
    for line in (result.stdout or "").splitlines():
        if "=" in line:
            key, _, value = line.partition("=")
            fields[key] = value.strip()
    return fields


def parse_heartbeat(dump):
    """Decode the hex columns of `qemu-io -c read -v` output into the heartbeat record."""
    data = bytearray()
    for line in (dump or "").splitlines():
        head, sep, rest = line.partition(":")
        if not sep or len(head.strip()) != 8:
            continue
        for token in rest.split()[:16]:
            if len(token) == 2:
                try:
                    data.append(int(token, 16))
                except ValueError:
                    pass
    text = bytes(data).split(b"\x00", 1)[0].decode("ascii", "replace").strip()
    parts = text.split()
    stamp = None
    if parts:
        try:
            stamp = float(parts[0])
        except ValueError:
            stamp = None
    return {"raw": text, "stamp": stamp, "boot_id": parts[1] if len(parts) > 1 else None}


def guest_sample(lab, reader, vm):
    command = (f'qemu-io -r -U -f qcow2 -c "read -v {HEARTBEAT_OFFSET} {HEARTBEAT_BYTES}" '
               f'/var/lib/nex-storage/*/nex-vms/{vm}/disk-0.qcow2 2>/dev/null')
    return parse_heartbeat(lab_mod.ssh(lab, reader, command, check=False).stdout)


def sample(lab, guests, reader, label):
    return {"label": label, "wall": time.time(),
            "guests": {vm: {"host": host,
                            "hostside": host_sample(lab, host, vm),
                            "guestside": guest_sample(lab, reader, vm)}
                       for vm, host in guests.items()}}


def compare(before, after, vm):
    host_before = before["guests"][vm]["hostside"]
    host_after = after["guests"][vm]["hostside"]
    guest_before = before["guests"][vm]["guestside"]
    guest_after = after["guests"][vm]["guestside"]
    changed = [f for f in CONTINUITY_FIELDS if host_before.get(f) != host_after.get(f)]
    if guest_before.get("boot_id") != guest_after.get("boot_id"):
        changed.append("guest_boot_id")
    advance = (guest_after.get("stamp") or 0) - (guest_before.get("stamp") or 0)
    return {"vm_id": vm, "host": before["guests"][vm]["host"], "changed": changed,
            "continuous": not changed, "heartbeat_advance_s": round(advance, 1),
            # Recorded, never a pass criterion: see the module docstring.
            "domstate_before": host_before.get("domstate"),
            "domstate_after": host_after.get("domstate")}


def report(before, after, guests):
    return [compare(before, after, vm) for vm in guests]


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--lab-dir", type=Path, required=True)
    parser.add_argument("--guests", required=True,
                        help="vm_uuid=host pairs, comma separated, e.g. UUID=core2,UUID=core3")
    parser.add_argument("--reader", default="core1",
                        help="lab host that reads the shared disks; must not run the guests")
    parser.add_argument("--evidence", type=Path, required=True)
    parser.add_argument("--label", required=True)
    parser.add_argument("--settle", type=float, default=0.0,
                        help="seconds to wait between the two samples (Arm A null control)")
    args = parser.parse_args()

    lab = lab_mod.check_lab(args.lab_dir)
    guests = dict(pair.split("=", 1) for pair in args.guests.split(","))
    assert args.reader not in guests.values(), "the reader must not run a sampled guest"
    args.evidence.mkdir(parents=True, exist_ok=True)

    before = sample(lab, guests, args.reader, args.label + "-before")
    if args.settle:
        time.sleep(args.settle)
    after = sample(lab, guests, args.reader, args.label + "-after")
    results = report(before, after, guests)
    payload = {"label": args.label, "before": before, "after": after, "results": results}
    (args.evidence / f"continuity-{args.label}.json").write_text(json.dumps(payload, indent=1) + "\n")
    for item in results:
        state = "CONTINUOUS" if item["continuous"] else "RESTARTED: " + ",".join(item["changed"])
        print(f'{item["host"]} {item["vm_id"][:8]}: {state} '
              f'heartbeat_advance={item["heartbeat_advance_s"]}s')
    return 0 if all(item["continuous"] for item in results) else 1


if __name__ == "__main__":
    sys.exit(main())
